/**
 * Optimal Huffman table limited to 16-bit codes, exactly as IJG's jpeg_gen_optimal_table
 * (including its tie-breaking and the reserved all-ones code point), so optimized files
 * come out byte-identical to libjpeg's.
 */
fun optimalHuffman(freqIn: LongArray): HuffSpec {
    val MAX_CLEN = 32
    val freq = LongArray(257); for (i in 0 until 256) freq[i] = freqIn[i]
    freq[256] = 1
    val codesize = IntArray(257); val others = IntArray(257) { -1 }
    while (true) {
        var c1 = -1; var v = 1_000_000_000L
        for (i in 0..256) if (freq[i] != 0L && freq[i] <= v) { v = freq[i]; c1 = i }
        var c2 = -1; v = 1_000_000_000L
        for (i in 0..256) if (freq[i] != 0L && freq[i] <= v && i != c1) { v = freq[i]; c2 = i }
        if (c2 < 0) break
        freq[c1] += freq[c2]; freq[c2] = 0
        codesize[c1]++
        while (others[c1] >= 0) { c1 = others[c1]; codesize[c1]++ }
        others[c1] = c2
        codesize[c2]++
        while (others[c2] >= 0) { c2 = others[c2]; codesize[c2]++ }
    }
    val bits = IntArray(MAX_CLEN + 1)
    for (i in 0..256) if (codesize[i] != 0) {
        check(codesize[i] <= MAX_CLEN) { "Huffman code size table overflow" }
        bits[codesize[i]]++
    }
    for (i in MAX_CLEN downTo 17) {
        while (bits[i] > 0) {
            var j = i - 2
            while (bits[j] == 0) j--
            bits[i] -= 2; bits[i - 1]++; bits[j + 1] += 2; bits[j]--
        }
    }
    var i = 16
    while (bits[i] == 0) i--
    bits[i]-- // remove the reserved code point
    val vals = ArrayList<Int>()
    for (len in 1..MAX_CLEN) for (j in 0..255) if (codesize[j] == len) vals.add(j)
    return HuffSpec(bits.copyOfRange(0, 17), vals.toIntArray())
}
