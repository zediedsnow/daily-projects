/** IJG quality scaling (jcparam.c jpeg_quality_scaling + jpeg_add_quant_table with force_baseline). */
fun scaledQuant(base: IntArray, quality: Int): IntArray {
    val q = quality.coerceIn(1, 100)
    val scale = if (q < 50) 5000 / q else 200 - q * 2
    return IntArray(64) { ((base[it].toLong() * scale + 50) / 100).toInt().coerceIn(1, 255) }
}

/** A Huffman table in the JPEG "BITS + HUFFVAL" form (bits[1..16]). */
class HuffSpec(val bits: IntArray, val vals: IntArray) {
    init { require(bits.size == 17) }
    /** Canonical code assignment (Annex C). Returns code and length per symbol. */
    fun codes(): Pair<IntArray, IntArray> {
        val code = IntArray(256); val size = IntArray(256)
        var c = 0; var k = 0
        for (len in 1..16) {
            repeat(bits[len]) {
                code[vals[k]] = c; size[vals[k]] = len; k++; c++
            }
            c = c shl 1
        }
        return code to size
    }
}

private fun bits(vararg b: Int) = intArrayOf(0) + b
private fun ints(vararg v: Int) = v

