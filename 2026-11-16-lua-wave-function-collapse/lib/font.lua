local M = {}

-- calls plot(x, y) for every lit pixel of text drawn at (x0, y0) with scale s
function M.draw(text, x0, y0, s, plot)
  local cx = x0
  for ch in text:gmatch(".") do
    local g = G[ch] or G[ch:upper()] or G[" "]
    for gy = 1, 5 do
      for gx = 1, 3 do
        if g[gy]:sub(gx, gx) == "#" then
          for yy = 0, s - 1 do
            for xx = 0, s - 1 do plot(cx + (gx - 1) * s + xx, y0 + (gy - 1) * s + yy) end
          end
        end
      end
    end
    cx = cx + 4 * s
  end
  return cx
end

function M.width(text, s) return #text * 4 * s - s end

return M
